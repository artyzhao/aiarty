function detectTheme(text) {
  for (var i = 0; i < WISH_THEMES.length; i++) {
    if (WISH_THEMES[i].re.test(text)) return WISH_THEMES[i];
  }
  return null;
}

/** 额外锚点：让祝福更贴肉 */
function extraAnchor(text, point) {
  var t = String(text || "");
  var m;
  if ((m = t.match(/(考研|初试|复试|面试|offer|涨薪|还贷|复合|表白|脱单|出国|云南|西藏|爸|妈|体检|失眠)[^。！？!?]{0,8}/))) {
    var s = m[0].replace(/\s+/g, "").slice(0, 12);
    if (s && point.indexOf(s) < 0) return s;
  }
  return "";
}

export function blessWish(text) {
  var t = String(text || "").trim();
  if (!t) return "先把心愿写清楚，星星才知道往哪照。";

  var h = hashStr(t);
  var h2 = (h >>> 8) || h;
  var h3 = (h >>> 16) || ((h * 2654435761) >>> 0);
  var point = extractPoint(t);
  var theme = detectTheme(t) || FALLBACK;
  var anchor = extraAnchor(t, point);

  var lead = pick(theme.name(point), h);
  var mid = pick(theme.bless, h2);
  var end = pick(theme.hold, h3);

  var anchorLine = "";
  if (anchor) {
    anchorLine = pick([
      "尤其是「" + anchor + "」这一截，我会重点记着。",
      "你不是泛泛许愿，是奔着「" + anchor + "」去的。",
      "「" + anchor + "」这几个字，就是愿望的落点。"
    ], h2 ^ h3);
  }

  var reply = (lead + mid + (anchorLine || "") + end)
    .replace(/\s+/g, "")
    .replace(/。{2,}/g, "。");
  if (!/。$/.test(reply)) reply += "。";

  if (reply.length > 110) {
    reply = (lead + mid + end).replace(/\s+/g, "").replace(/。{2,}/g, "。");
    if (reply.length > 110) reply = reply.slice(0, 108).replace(/[，。、]+$/, "") + "。";
  }
  return reply;
}

