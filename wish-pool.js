/**
 * 许愿池祝福：抓住心愿要点（本地拼装，无需联网）。
 * 结构：点名心愿 → 贴题祝福 → 落地收束（少套话）
 */

function hashStr(s) {
  var h = 2166136261;
  for (var i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

function pick(arr, h) {
  var n = arr.length;
  if (!n) return "";
  return arr[(h >>> 0) % n];
}

/** 抽出心愿要点：去掉「希望/我想」外壳，保留具体所求 */
function extractPoint(text) {
  var t = String(text || "")
    .replace(/[\r\n]+/g, " ")
    .replace(/[“”"‘’']/g, "")
    .replace(/\s+/g, " ")
    .trim();

  var parts = t.split(/[。！？!?；;…]+/).map(function (p) {
    return p.replace(/^[，,、\s]+|[，,、\s]+$/g, "").trim();
  }).filter(function (p) { return p.length >= 2; });

  var best = parts[0] || t;
  if (parts.length > 1) {
    for (var i = 0; i < parts.length; i++) {
      if (/考研|考试|面试|offer|复合|表白|涨薪|赚钱|健康|爸|妈|旅行|出国|上岸|脱单|结婚|还贷|升职/.test(parts[i])) {
        best = parts[i];
        break;
      }
      if (parts[i].length >= 4 && parts[i].length <= 28) best = parts[i];
    }
  }

  best = best
    .replace(/^(我希望|希望|我想要|我想|我愿|愿我|愿|祈求|拜托|求你|求|请让我|请给我|请|能不能|可以让我|让我|给我|我想许个愿|许个愿|许愿)/, "")
    .replace(/^(能够|可以|顺利|真的|一定要|一定|顺利地|早点|尽快)/, "")
    .trim();

  if (best.length > 22) best = best.slice(0, 22).replace(/[，,、\s]+$/, "") + "…";
  if (best.length < 2) {
    best = t.slice(0, 16).replace(/[，,、\s]+$/, "");
    if (t.length > 16) best += "…";
  }
  return best;
}

function q(point) {
  return point ? "「" + point + "」" : "这份心愿";
}

