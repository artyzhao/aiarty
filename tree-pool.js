/**
 * 树洞回复：抓住留言要点 + 同理心（本地拼装，无需联网）。
 * 结构：共情复述 → 贴合要点的回应 → 温和收束（不说教）
 */

function hashStr(s) {
  var h = 2166136261;
  for (var i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

function pick(arr, h) {
  var n = arr.length;
  if (!n) return "";
  return arr[(h >>> 0) % n];
}

/** 清洗并抽出最能代表「要点」的短句（尽量保留动词/对象，不只截前几字） */
function extractPoint(text) {
  var t = String(text || "")
    .replace(/[\r\n]+/g, " ")
    .replace(/[“”"‘’']/g, "")
    .replace(/\s+/g, " ")
    .trim();

  // 按句号/问号拆，取信息量最大的一句
  var parts = t.split(/[。！？!?；;…]+/).map(function (p) {
    return p.replace(/^[，,、\s]+|[，,、\s]+$/g, "").trim();
  }).filter(function (p) { return p.length >= 2; });

  var best = parts[0] || t;
  if (parts.length > 1) {
    // 优先含情绪或具体事件的分句
    for (var i = 0; i < parts.length; i++) {
      if (/累|难过|哭|怕|慌|气|恨|孤独|想|分手|加班|面试|爸|妈|催|不够|没用|睡不|撑|崩|冷|空/.test(parts[i])) {
        best = parts[i];
        break;
      }
      if (parts[i].length > best.length && parts[i].length <= 28) best = parts[i];
    }
  }

  best = best
    .replace(/^(其实|就是|反正|唉+|啊+|嗯+|那个|今天|今晚|这几天|最近|有时候|说实话|我想说|我想|我只是想|我只想|我感觉|我觉得|我有点|我好|我真的|说真的)/, "")
    .replace(/^(有点|非常|特别|真的|好|很|太)+/, "")
    .trim();

  if (best.length > 24) best = best.slice(0, 24).replace(/[，,、\s]+$/, "") + "…";
  if (best.length < 2) {
    best = t.slice(0, 18).replace(/[，,、\s]+$/, "");
    if (t.length > 18) best += "…";
  }
  return best;
}

function q(point) {
  return point ? "「" + point + "」" : "你写的这些";
}

