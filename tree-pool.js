function detectFeeling(text) {
  for (var i = 0; i < FEELINGS.length; i++) {
    if (FEELINGS[i].re.test(text)) return FEELINGS[i];
  }
  return null;
}

/** 从原文再抓一个「细节锚点」（人名指代、具体动作），让回复更贴 */
function extraAnchor(text, point) {
  var t = String(text || "");
  var m;
  if ((m = t.match(/(他|她|TA|对方|老板|同事|爸|妈|父母|前任|男友|女友)[^。！？!?]{0,10}/))) {
    var s = m[0].replace(/\s+/g, "").slice(0, 12);
    if (s && point.indexOf(s) < 0) return s;
  }
  if ((m = t.match(/(加班|面试|考试|冷战|催婚|相亲|分手|复合|失眠|熬夜)[^。！？!?]{0,6}/))) {
    var s2 = m[0].replace(/\s+/g, "").slice(0, 10);
    if (s2 && point.indexOf(s2) < 0) return s2;
  }
  return "";
}

export function replyTree(text) {
  var t = String(text || "").trim();
  if (!t) return "树洞还空着。当你想说点什么，写进来就好，我会安静听，也会认真回你。";

  var h = hashStr(t);
  var h2 = (h >>> 8) || h;
  var h3 = (h >>> 16) || ((h * 2654435761) >>> 0);
  var point = extractPoint(t);
  var feeling = detectFeeling(t) || FALLBACK;
  var anchor = extraAnchor(t, point);

  var lead = pick(feeling.empathize(point), h);
  var mid = pick(feeling.mirror, h2);
  var end = pick(feeling.hold, h3);

  // 若有额外锚点，插一句更贴肉的承接
  var anchorLine = "";
  if (anchor) {
    anchorLine = pick([
      "尤其是你提到的「" + anchor + "」，这一下最扎人。",
      "「" + anchor + "」这几个字里，我听得出你卡在哪里。",
      "你不是泛泛而谈，是「" + anchor + "」这件事正在磨你。"
    ], h2 ^ h3);
  }

  var reply = lead + mid + (anchorLine || "") + end;
  reply = reply.replace(/\s+/g, "").replace(/。{2,}/g, "。");
  if (!/。$/.test(reply)) reply += "。";

  if (reply.length > 140) {
    // 优先保住共情开头 + 收束
    reply = (lead + mid + end).replace(/\s+/g, "").replace(/。{2,}/g, "。");
    if (reply.length > 140) reply = reply.slice(0, 138).replace(/[，。、]+$/, "") + "。";
  }
  return reply;
}

